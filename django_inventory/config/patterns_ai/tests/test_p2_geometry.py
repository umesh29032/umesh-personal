class UnitsAndSvgTests(TestCase):
    def test_um_conversions(self):
        self.assertEqual(mm_to_um('150.0004'), 150000)
        self.assertEqual(mm_to_um('150.0006'), 150001)
        self.assertEqual(str(um_to_mm(150049)), '150.0')
        self.assertEqual(str(um_to_mm(150050)), '150.1')

    def test_validate_canonical(self):
        good = dict(GeometryServiceTests.FAKE_GEO)
        self.assertEqual(validate_canonical_geometry(good), [])
        bad = dict(good, outer=list(reversed(good['outer'])))
        self.assertTrue(any('winding' in p
                            for p in validate_canonical_geometry(bad)))
        closed = dict(good, outer=good['outer'] + [good['outer'][0]])
        self.assertTrue(any('closed' in p
                            for p in validate_canonical_geometry(closed)))
        offset = dict(good, outer=[[x + 5, y] for x, y in good['outer']])
        self.assertTrue(any('origin' in p
                            for p in validate_canonical_geometry(offset)))
        floats = dict(good, outer=[[0.5, 0], [10, 0], [10, 10]])
        self.assertTrue(any('non-integer' in p
                            for p in validate_canonical_geometry(floats)))
        self.assertEqual(validate_canonical_geometry({'schema_version': 99}),
                         ['schema_version missing or unsupported'])

    def test_svg_render(self):
        payload = dict(GeometryServiceTests.FAKE_GEO)
        payload['features'] = dict(payload['features'],
                                   grain={'angle_cdeg': 9000})
        svg = geometry_svg(payload, true_scale=True)
        self.assertIn('<svg', svg)
        # true-scale span = piece + 2x5 mm pad, matching the viewBox exactly
        # (mismatch = silent print shrink — the Gate-1 bug this pins against)
        self.assertIn('width="160.0mm"', svg)
        self.assertIn('viewBox="-5 -5 160.0 110.0"', svg)
        self.assertIn('pai-grain-arrow', svg)
        self.assertIn('data-w-mm="150.0"', svg)
        svg2 = geometry_svg(payload)
        self.assertIn('width="100%"', svg2)
