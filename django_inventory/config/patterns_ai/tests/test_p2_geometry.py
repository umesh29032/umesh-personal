# small fast board: 8x6 squares of 50 mm => 400x300 mm mat, 35 inner corners
BOARD = {'schema_version': 1, 'squares_x': 8, 'squares_y': 6,
         'square_mm': 50.0, 'marker_mm': 37.0,
         'aruco_dict': 'DICT_5X5_1000'}
# first inner-corner row has 7 corners: ids 0..6 span 6 squares = 300 mm
TAPE = {'schema_version': 1,
        'distances': [{'from_id': 0, 'to_id': 6, 'expected_mm': 300.0}]}
# ground-truth piece: 150x100 mm rectangle, inside the 20 mm keep-out
PIECE_MM = [[100, 80], [250, 80], [250, 180], [100, 180]]

RUNTIME_OK = compute_bridge.runtime_available()


def synth_golden(name, **over):
    """Render a golden capture via the runtime; returns PNG bytes."""
    out_img = SYNTH_DIR / f'{name}.png'
    job = {'board_spec': BOARD, 'out_image': str(out_img),
           'piece_polygon_mm': PIECE_MM, 'tilt': 0.06, 'yaw': 0.04,
           'blur': 1}
    job.update(over)
    res = compute_bridge.run_tool('synth', job)
    assert res['ok'], res
    return out_img.read_bytes()


